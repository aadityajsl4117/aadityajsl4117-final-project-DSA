const generateCopies = (bookId: string, count: number, shelf: string): BookCopy[] => {
  return Array.from({ length: count }, (_, i) => ({
    copyId: `${bookId}-C${i + 1}`,
    bookId,
    barcode: `LIB-${bookId}-C${i + 1}`,
    condition: i % 2 === 0 ? 'NEW' : 'GOOD',
    shelf,
    status: CopyStatus.AVAILABLE,
    borrowedBy: null,
    lastBorrowDate: null,
  }));
};

